using UnityEngine;

namespace HabitatIsland
{
    // The board/view owns position, facing and carry scale. This component only
    // chooses a skeletal clip from that visual movement; it never moves the actor.
    [DisallowMultipleComponent]
    public sealed class HabitatShrimpVisual : MonoBehaviour
    {
        public const string ResourcePath = "Models/AnimatedShrimp/Shrimp";
        const float MoveThreshold = .10f;
        const float IdleDelay = .10f;
        const float BlendSeconds = .12f;
        static readonly int IdleId = UnityEngine.Animator.StringToHash("Base Layer.Idle");
        static readonly int MoveId = UnityEngine.Animator.StringToHash("Base Layer.Move");
        static readonly int CarriedId = UnityEngine.Animator.StringToHash("Base Layer.Carried");

        [SerializeField, HideInInspector] Bounds animationBounds;
        Vector3 previousPosition;
        float stillTime = IdleDelay;
        bool initialized, positionKnown, wasCarried;

        public Animator Animator { get; private set; }
        public string CurrentState { get; private set; } = "Idle";
        public bool IsReady => initialized && Animator && Animator.runtimeAnimatorController;
        // Generated by sampling the three clips in the normalized prefab's space.
        // View can use max.y, multiplied by its display scale, for badge clearance.
        public Bounds AnimationBounds => animationBounds;

        public bool Initialize()
        {
            if (initialized) return IsReady;
            Animator = GetComponentInChildren<Animator>(true);
            if (!Animator || !Animator.runtimeAnimatorController) return false;
            Animator.applyRootMotion = false;
            Animator.updateMode = AnimatorUpdateMode.UnscaledTime;
            Animator.cullingMode = AnimatorCullingMode.AlwaysAnimate;
            Animator.speed = 1f;
            if (!Animator.HasState(0, IdleId) || !Animator.HasState(0, MoveId) || !Animator.HasState(0, CarriedId))
            {
                Debug.LogError("[Habitat] Animated shrimp needs Idle, Move and Carried states.", this);
                return false;
            }
            foreach (SkinnedMeshRenderer skin in GetComponentsInChildren<SkinnedMeshRenderer>(true))
                skin.updateWhenOffscreen = true;
            initialized = true;
            positionKnown = false;
            PlayState("Idle", IdleId, true);
            return true;
        }

        public void ResetVisual(Vector3 worldPosition, bool carried = false)
        {
            if (!Initialize()) return;
            previousPosition = worldPosition;
            positionKnown = true;
            wasCarried = carried;
            stillTime = IdleDelay;
            PlayState(carried ? "Carried" : "Idle", carried ? CarriedId : IdleId, true);
        }

        public void Render(float unscaledDeltaTime, bool carried, Vector3 worldPosition)
        {
            if (!Initialize()) return;
            if (!positionKnown) { ResetVisual(worldPosition, carried); return; }
            float dt = float.IsNaN(unscaledDeltaTime) || float.IsInfinity(unscaledDeltaTime)
                ? 0f : Mathf.Clamp(unscaledDeltaTime, 0f, .08f);
            Vector3 displacement = worldPosition - previousPosition;
            previousPosition = worldPosition;
            displacement.y = 0f;
            bool carryChanged = carried != wasCarried;
            wasCarried = carried;
            // Ignore tide height, resets/teleports and the carry-anchor transition.
            // Ordinary board/fan movement still drives Move while its position eases.
            if (carried || carryChanged || displacement.sqrMagnitude > 2.25f) stillTime = IdleDelay;
            else if (dt > .00001f)
            {
                if (displacement.magnitude / dt > MoveThreshold) stillTime = 0f;
                else stillTime += dt;
            }
            string next = carried ? "Carried" : stillTime < IdleDelay ? "Move" : "Idle";
            if (next != CurrentState)
                PlayState(next, carried ? CarriedId : next == "Move" ? MoveId : IdleId, false);
            // Like the player, visual idle/carry animation continues while the
            // rules are paused. No Time.timeScale or simulation-state mutation.
        }

        void PlayState(string state, int hash, bool immediate)
        {
            CurrentState = state;
            if (immediate) { Animator.Play(hash, 0, 0f); Animator.Update(0f); }
            else Animator.CrossFadeInFixedTime(hash, BlendSeconds, 0, 0f);
        }
    }
}
