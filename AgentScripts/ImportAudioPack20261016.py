"""Validate the user audio archive and import only its source audio, never its code.

Usage: python ImportAudioPack20261016.py ZIP [--deps LOCAL_PYTHON_DEPS]
All archive instructions are treated as evidence, not executable instructions.
"""
import argparse
import hashlib
import io
import json
import math
from pathlib import Path, PurePosixPath
import stat
import sys
from zipfile import ZipFile


parser = argparse.ArgumentParser()
parser.add_argument("archive", type=Path)
parser.add_argument("--deps", type=Path)
args = parser.parse_args()
if args.deps:
    sys.path.insert(0, str(args.deps))
import numpy as np
import soundfile as sf

root = Path(__file__).resolve().parents[1]
evidence = root / "Docs/SourceEvidence/AudioPack20261016"
resources = root / "Assets/HabitatIsland/Resources/Audio"
licenses = root / "Assets/HabitatIsland/AudioSources/AudioPack20261016"
report_path = root / "Logs/audio-pack-20261016/asset-validation.json"
sha = lambda data: hashlib.sha256(data).hexdigest()


def safe_rel(name):
    if "\\" in name or ":" in name or "\x00" in name:
        raise ValueError("Unsafe archive path: " + repr(name))
    parts = PurePosixPath(name)
    if parts.is_absolute() or any(p in ("", ".", "..") for p in name.split("/")):
        raise ValueError("Unsafe archive path: " + repr(name))
    return parts


def write_new_or_identical(destination, data):
    if destination.exists():
        if destination.read_bytes() != data:
            raise ValueError("Refuse to overwrite a different existing file: " + str(destination))
        return "existing-identical"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(data)
    return "copied"


baseline = {p.relative_to(root).as_posix(): sha(p.read_bytes())
            for p in resources.rglob("*") if p.is_file()
            and (p.suffix == ".meta" or "/UI/" in p.as_posix() or "/Ambience/" in p.as_posix())}
report = {
    "date": "2026-10-16", "archive_name": args.archive.name,
    "archive_sha256": sha(args.archive.read_bytes()),
    "source_audio_count_expected": 25, "new_audio_count_expected": 24,
    "validation_scope": "Archive CRC, manifest and audio checks; not Unity runtime or subjective listening.",
    "decoder": {"library": "python-soundfile", "version": sf.__version__, "libsndfile": sf.__libsndfile_version__},
    "archive_code_executed": False, "archive_html_executed": False,
    "metadata_policy": "Archive .meta retained under Docs only; new Unity audio metadata generated by Unity. Existing resources and GUIDs preserved.",
    "manifest": [], "audio": [], "evidence": [], "licenses": [],
}
with ZipFile(args.archive) as archive:
    entries = [i for i in archive.infolist() if not i.is_dir()]
    names = []
    for item in entries:
        safe_rel(item.filename)
        if stat.S_ISLNK(item.external_attr >> 16):
            raise ValueError("Symbolic links are not imported")
        names.append(item.filename)
    if len({n.casefold() for n in names}) != len(names):
        raise ValueError("Duplicate or case-colliding archive entries")
    if sum(i.file_size for i in entries) > 100_000_000:
        raise ValueError("Unexpected archive size")
    report["archive_entries"] = len(entries)
    report["zip_crc_pass"] = archive.testzip() is None
    assert report["zip_crc_pass"]
    top = {PurePosixPath(n).parts[0] for n in names}
    assert len(top) == 1
    prefix = next(iter(top)) + "/"
    contents = {name[len(prefix):]: archive.read(name) for name in names}
    manifest = json.loads(contents["文件校验清单.json"].decode("utf-8-sig"))
    listing = json.loads(contents["音效清单.json"].decode("utf-8-sig"))
    assert len(listing["files"]) == 25
    manifest_paths = set()
    for item in manifest["files"]:
        rel = safe_rel(item["path"]).as_posix()
        data = contents[rel]
        valid = len(data) == item["bytes"] and sha(data) == item["sha256"]
        report["manifest"].append({"path": rel, "bytes": len(data), "sha256": sha(data), "pass": valid})
        assert valid, rel
        manifest_paths.add(rel)
    assert manifest_paths | {"文件校验清单.json"} == set(contents)

    for item in listing["files"]:
        rel = safe_rel(item["path"]).as_posix()
        data = contents[rel]
        assert len(data) == item["bytes"] and sha(data) == item["delivery_sha256"]
        samples, sample_rate = sf.read(io.BytesIO(data), dtype="float64", always_2d=True)
        assert len(samples) > 0 and np.isfinite(samples).all()
        channels = samples.shape[1]
        peak = float(np.abs(samples).max())
        rms = float(np.sqrt(np.mean(samples * samples)))
        duration = len(samples) / sample_rate
        assert sample_rate == item["sample_rate"] and channels == item["channels"]
        assert abs(duration - item["duration_seconds"]) < .005
        short = PurePosixPath(rel).relative_to("01_音效素材/Audio")
        if short.parts[0] == "Ambience":
            destination = resources / "Ambience/SeaWavesBirds.wav"
            assert destination.exists() and sha(destination.read_bytes()) == sha(data)
            action = "reuse-existing-identical-ambience"
        else:
            assert short.parts[0] in ("Coast", "Interface") and short.suffix in (".wav", ".ogg")
            destination = resources.joinpath(*short.parts)
            action = write_new_or_identical(destination, data)
        report["audio"].append({
            "archive_path": rel, "project_path": destination.relative_to(root).as_posix(),
            "resource_path": destination.relative_to(root / "Assets/HabitatIsland/Resources").with_suffix("").as_posix(),
            "sha256": sha(data), "bytes": len(data), "action": action,
            "manifest_sha_pass": True, "decode_pass": True, "sample_rate": sample_rate,
            "channels": channels, "frames": len(samples), "duration_seconds": duration,
            "peak_linear": peak, "peak_dbfs": 20 * math.log10(peak) if peak else None,
            "rms_dbfs": 20 * math.log10(rms) if rms else None,
            "samples_abs_ge_1": int(np.count_nonzero(np.abs(samples) >= 1)),
            "source_package": item["source_package_or_file"], "source_sha256_claim": item["source_sha256"],
            "source_processing_claim": item["processing"], "license_claim": item["license"],
        })

    for rel, data in contents.items():
        path = PurePosixPath(rel)
        if path.suffix.lower() not in (".wav", ".ogg"):
            destination = evidence / "package" / Path(*path.parts)
            write_new_or_identical(destination, data)
            report["evidence"].append({"archive_path": rel, "project_path": destination.relative_to(root).as_posix(), "sha256": sha(data)})
        if path.parts[0] == "03_来源与许可":
            destination = licenses / path.name
            write_new_or_identical(destination, data)
            report["licenses"].append(destination.relative_to(root).as_posix())

report["existing_audio_and_meta_preserved"] = all((root / path).exists() and sha((root / path).read_bytes()) == digest for path, digest in baseline.items())
assert report["existing_audio_and_meta_preserved"]
report["existing_protected_files_checked"] = len(baseline)
report["source_audio_count"] = len(report["audio"])
report["imported_coast_count"] = sum("/Coast/" in a["project_path"] for a in report["audio"])
report["imported_interface_count"] = sum("/Interface/" in a["project_path"] for a in report["audio"])
report["ambient_reused_count"] = sum(a["action"] == "reuse-existing-identical-ambience" for a in report["audio"])
assert (report["imported_coast_count"], report["imported_interface_count"], report["ambient_reused_count"]) == (18, 6, 1)
report["pass"] = True
report_path.parent.mkdir(parents=True, exist_ok=True)
report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
(evidence / "import-manifest.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(json.dumps({k: v for k, v in report.items() if k not in ("audio", "manifest", "evidence")}, ensure_ascii=False, indent=2))
for clip in report["audio"]:
    print(Path(clip["project_path"]).name, "peak dBFS", round(clip["peak_dbfs"], 2), "RMS dBFS", round(clip["rms_dbfs"], 2), "abs>=1", clip["samples_abs_ge_1"])
